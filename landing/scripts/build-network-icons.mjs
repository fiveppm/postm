// postmonster: generates src/data/network-icons.ts from simple-icons (CC0).
// Simple-icons only carries marks the brands allow to be redistributed, so
// networks without an official mark get `icon: null` in networks.ts and are
// rendered as monogram tiles — never as an invented logo.
//
// Usage (from landing/):
//   node scripts/build-network-icons.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const nodeRequire = createRequire(import.meta.url);
const si = nodeRequire('simple-icons');

const __dirname = dirname(fileURLToPath(import.meta.url));
const landingRoot = resolve(__dirname, '..');
const networksFile = join(landingRoot, 'src', 'data', 'networks.ts');
const outFile = join(landingRoot, 'src', 'data', 'network-icons.ts');

const bySlug = new Map();
for (const key of Object.keys(si)) {
  const icon = si[key];
  if (icon && icon.slug) bySlug.set(icon.slug, icon);
}

const src = readFileSync(networksFile, 'utf8');
const keys = [...new Set([...src.matchAll(/icon:\s*'([^']+)'/g)].map((m) => m[1]))];

const missing = keys.filter((k) => !bySlug.has(k));
if (missing.length) {
  console.error('build-network-icons: no simple-icons mark for:', missing.join(', '));
  console.error('Set `icon: null` for those in networks.ts (monogram fallback) or fix the key.');
  process.exit(1);
}

const entries = keys
  .sort()
  .map((k) => {
    const { path, hex, title } = bySlug.get(k);
    return `  ${JSON.stringify(k)}: { title: ${JSON.stringify(title)}, hex: ${JSON.stringify(hex)}, path: ${JSON.stringify(path)} },`;
  })
  .join('\n');

const out = `// GENERATED by scripts/build-network-icons.mjs — do not edit by hand.
// Mark data from simple-icons (https://simpleicons.org, CC0-1.0).
export const networkIcons: Record<
  string,
  { title: string; hex: string; path: string }
> = {
${entries}
};
`;

writeFileSync(outFile, out);
console.log(`build-network-icons: wrote ${keys.length} icons -> src/data/network-icons.ts`);
